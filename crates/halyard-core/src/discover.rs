//! The discovery seam (§6, §7.3): the [`EcosystemAdapter`] trait, the
//! [`DiscoverCtx`] input the orchestrator hands to adapters, and the
//! [`RawPackage`]/[`RawDep`] rows adapters return before the orchestrator
//! merges them into a [`Workspace`].
//!
//! Design notes:
//!
//! * Adapters are **pure**: they receive the committed file inventory and
//!   manifest contents through [`DiscoverCtx`] and never read the
//!   filesystem or spawn processes (invariant I5/I6). The orchestrator
//!   (`halyard-discover`) owns the walk and the reads.
//! * Everything is a plain-data row with `String` names; the orchestrator
//!   interns them into the [`Workspace`] interner (§5.1).
//! * The trait carries **only** what this milestone implements
//!   (`discover`). The §7.3 methods that mutate manifests and lockfiles
//!   (`edit_versions`, `patch_lockfile`, `publish`, …) are deliberately
//!   absent until the mutation engine lands (M3/M5); shipping a stubbed
//!   method is forbidden (TASK §2.2). The omission is tracked as a slice-C
//!   task in `PROGRESS.md`.

use std::collections::{BTreeMap, BTreeSet};

use bstr::BString;
use semver::Version;

use crate::id::{PkgId, Sym};
use crate::package::{DepKind, Ecosystem, ManifestSite, PathFilter, ReqSpec, Span, TagTemplate};

/// The orchestrator-provided view of the repository (§6.1/§7.3): the
/// committed file inventory plus the contents of every manifest-shaped
/// file. Deterministic by construction — both containers are ordered by
/// [`RelPath`], so adapter iteration order never depends on filesystem
/// order (invariant I3).
///
/// [`RelPath`]: crate::package::RelPath
#[derive(Clone, Debug, Default)]
pub struct DiscoverCtx {
    tree: BTreeSet<RelPathKey>,
    contents: BTreeMap<RelPathKey, BString>,
}

/// Newtype so both maps stay sorted by path text.
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
struct RelPathKey(BString);

impl RelPathKey {
    fn new(path: &str) -> Option<Self> {
        crate::package::RelPath::new(path).map(|_| Self(BString::from(path)))
    }
    fn as_str(&self) -> &str {
        std::str::from_utf8(&self.0).unwrap_or_default()
    }
}

impl DiscoverCtx {
    /// Empty context.
    pub fn new() -> Self {
        Self::default()
    }

    /// Registers one file (its inventory entry and its bytes). Returns
    /// `false` when `path` is not a normalized repo-relative path — the
    /// file is then ignored rather than half-registered.
    pub fn insert_file(&mut self, path: &str, bytes: Vec<u8>) -> bool {
        let Some(key) = RelPathKey::new(path) else {
            return false;
        };
        self.tree.insert(key.clone());
        self.contents.insert(key, BString::from(bytes));
        true
    }

    /// Contents of one registered file (`None` for inventory-only paths).
    pub fn file(&self, path: &str) -> Option<&[u8]> {
        self.contents.get(&RelPathKey(BString::from(path))).map(|b| b.as_ref())
    }

    /// The committed file inventory, sorted by path.
    pub fn tree(&self) -> impl Iterator<Item = &str> + '_ {
        self.tree.iter().map(RelPathKey::as_str)
    }

    /// All directories implied by the inventory (every proper ancestor of
    /// every file), sorted. Root is not listed (its path is empty).
    pub fn dirs(&self) -> Vec<&str> {
        let mut out: BTreeSet<&str> = BTreeSet::new();
        for key in &self.tree {
            let path = key.as_str();
            let mut offset = 0usize;
            while let Some(idx) = path.get(offset..).and_then(|s| s.find('/')) {
                let end = offset + idx;
                if end > 0 {
                    if let Some(dir) = path.get(..end) {
                        out.insert(dir);
                    }
                }
                offset = end + 1;
            }
        }
        out.into_iter().collect()
    }

    /// Registered files whose path ends with `suffix`, sorted by path.
    pub fn files_with_suffix(&self, suffix: &str) -> Vec<&str> {
        self.contents
            .keys()
            .map(RelPathKey::as_str)
            .filter(|p| p.ends_with(suffix))
            .collect()
    }
}

/// Where a [`RawPackage`]'s version is written — the raw-string mirror of
/// [`VersionSource`](crate::package::VersionSource) before interning.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum RawVersionSource {
    /// Written in the package's own manifest.
    Local,
    /// Inherited from a workspace manifest (e.g. `version.workspace =
    /// true`); `file` is the authoritative manifest, `key_path` the key
    /// inside it (§6.3).
    WorkspaceInherited {
        /// Authoritative manifest (repo-relative).
        file: String,
        /// Key path inside that manifest (e.g. `package.version`).
        key_path: String,
    },
    /// Generated by a tool; not editable in place.
    Dynamic,
}

/// Facets collected during discovery that feed the polyglot link rules
/// (§6.5). Plain data; a facet is `true` only when the manifest proves it.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Facets {
    /// Cargo `crate-type` contains `"cdylib"` (native-binding crates).
    pub cdylib: bool,
    /// Cargo package depends on `wasm-bindgen` (wasm-pack layout, §6.5).
    pub wasm_bindgen: bool,
    /// npm `package.json` carries a `napi` key or an `@napi-rs/cli`
    /// dependency (napi-rs layout, §6.5).
    pub napi: bool,
}

/// One dependency row as written in a manifest, before the orchestrator
/// resolves the target package (§5.3 `DepEdge`).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RawDep {
    /// Dependency name (for Cargo renames this is the **real** package
    /// name from the `package = "…"` key, §6.3).
    pub name: String,
    /// Edge kind.
    pub kind: DepKind,
    /// Requirement as written.
    pub req: ReqSpec,
    /// Where the requirement text lives (the edit site, §9.1).
    pub site: ManifestSite,
    /// The requirement text **as written** (sliced from the manifest at
    /// the site's first span; empty when synthesized). Carried so the
    /// planner's rewriter preserves the original operator style
    /// (`0.4` → `0.5`, not `^0.5`; appendix A.2, ADR-0008).
    pub raw: BString,
    /// True when the manifest **proves** the requirement targets a
    /// workspace member (`workspace = true`, a `workspace:`/`file:`/
    /// `link:`/`catalog:` protocol, or a repo-internal path). Plain
    /// version requirements are registry-resolved by cargo/pnpm even when
    /// the name matches a member, so they are *not* internal (this is
    /// what makes the differential comparison against `cargo metadata`
    /// exact).
    pub internal: bool,
}

/// A non-fatal observation made during discovery (§6.3: packages without a
/// version are treated as unpublishable *and warned*; `[patch]` sections
/// are ignored with a warning).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct DiscoveryWarning {
    /// Stable warning tag, e.g. `no-version`, `external-dep`,
    /// `ignored-section`.
    pub code: &'static str,
    /// Subject the warning is about (package name or manifest path).
    pub subject: String,
    /// Human-readable detail (rendered by `halyard doctor`, M1.10).
    pub message: String,
}

/// One discovered package row (§5.3, pre-merge). The orchestrator assigns
/// [`PkgId`]s, interns names and resolves `deps` against the merged set.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RawPackage {
    /// Package name (crate name or npm name, scoped names included).
    pub name: String,
    /// Ecosystem (adapters produce built-ins only).
    pub ecosystem: Ecosystem,
    /// Package root directory, repo-relative and forward-slash normalized
    /// (empty string = repo root, §6.1 single-package mode).
    pub root: String,
    /// Manifest path (e.g. `crates/a/Cargo.toml`).
    pub manifest: String,
    /// Current version (`None` = no/invalid version in the manifest;
    /// unpublishable, warned, §6.3).
    pub version: Option<Version>,
    /// Where the version comes from.
    pub version_source: RawVersionSource,
    /// Whether the package may be published (`publish = false` /
    /// `private: true`, §6.3/§6.4).
    pub publishable: bool,
    /// Outgoing dependency rows (resolved to edges at merge time).
    pub deps: Vec<RawDep>,
    /// Tag template override (`package.metadata.halyard.tag_style`); `None`
    /// keeps the group default (appendix A.3).
    pub tag_template: Option<TagTemplate>,
    /// Changelog file, when the manifest names one.
    pub changelog: Option<String>,
    /// Byte site of the package's own version value (see
    /// [`crate::package::Package::version_site`]): the file plus the span
    /// of the version text. `None` when the package has no usable version
    /// or the value is not editable in place.
    pub version_site: Option<ManifestSite>,
    /// include/exclude globs (currently only via config overrides; the
    /// default filter accepts everything).
    pub include: PathFilter,
    /// Link-rule facets (§6.5).
    pub facets: Facets,
    /// Non-fatal observations (§6.3).
    pub warnings: Vec<DiscoveryWarning>,
}

/// Manifest syntax of a [`DiscoverError::Manifest`] failure.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ManifestFormat {
    /// `Cargo.toml` (parsed with `toml_edit` spans, §6.2).
    Toml,
    /// `package.json` (hand-written span scanner per ADR-0001, §6.4).
    Json,
    /// `pnpm-workspace.yaml` (restricted YAML subset scanner, §19.2).
    Yaml,
}

/// Discovery errors (§15.4 `E-DISC-*`). Every variant carries a stable
/// code documented at `docs/errors/`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum DiscoverError {
    /// A filesystem step of the orchestrator walk failed
    /// (`E-DISC-IO`).
    Io {
        /// The path the orchestrator tried to read.
        path: String,
        /// The underlying `io::Error` text.
        message: String,
    },
    /// A manifest failed to parse or carries an impossible combination
    /// (`E-DISC-MANIFEST`).
    Manifest {
        /// Repo-relative manifest path.
        file: String,
        /// Manifest syntax.
        format: ManifestFormat,
        /// What is wrong (rendered with source context by the CLI).
        message: String,
        /// Byte span of the offending text, when known.
        span: Option<Span>,
    },
    /// A workspace member defines its own `[workspace]` — nested
    /// workspaces are rejected with guidance (§6.3, `E-DISC-NESTED-WS`).
    NestedWorkspace {
        /// Manifest of the enclosing workspace root.
        outer: String,
        /// Manifest of the nested workspace root.
        inner: String,
    },
    /// A member pattern is not a supported glob or matches nothing
    /// (`E-DISC-GLOB`).
    Glob {
        /// The offending pattern.
        pattern: String,
        /// Detail (parse failure vs zero matches).
        message: String,
    },
    /// The repository contains neither a workspace nor a package
    /// (`E-DISC-NO-PACKAGE`).
    NoPackage,
    /// Two packages in one ecosystem claim the same name
    /// (`E-DISC-DUPLICATE`).
    Duplicate {
        /// The duplicated name.
        name: String,
        /// Manifest of the first occurrence.
        first: String,
        /// Manifest of the second occurrence.
        second: String,
    },
    /// A `[[link]]` entry names a package that discovery did not find
    /// (`E-DISC-LINK-UNKNOWN`).
    UnknownLink {
        /// The unknown package name.
        name: String,
    },
}

impl DiscoverError {
    /// Stable §15.4 code of this error (used as the miette report code
    /// from M1.10 and as the `docs/errors/` page selector).
    pub fn code(&self) -> &'static str {
        match self {
            Self::Io { .. } => "E-DISC-IO",
            Self::Manifest { .. } => "E-DISC-MANIFEST",
            Self::NestedWorkspace { .. } => "E-DISC-NESTED-WS",
            Self::Glob { .. } => "E-DISC-GLOB",
            Self::NoPackage => "E-DISC-NO-PACKAGE",
            Self::Duplicate { .. } => "E-DISC-DUPLICATE",
            Self::UnknownLink { .. } => "E-DISC-LINK-UNKNOWN",
        }
    }
}

impl std::fmt::Display for DiscoverError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Io { path, message } => {
                write!(f, "failed to read {path}: {message}")
            }
            Self::Manifest {
                file,
                format,
                message,
                span,
            } => {
                write!(f, "invalid {format:?} manifest {file}: {message}")?;
                if let Some(span) = span {
                    write!(f, " (at byte {}..{})", span.start, span.end)?;
                }
                Ok(())
            }
            Self::NestedWorkspace { outer, inner } => write!(
                f,
                "nested workspace: {inner} defines its own [workspace] while already being a \
                 member of {outer}; split the repo or exclude {inner} from {outer}"
            ),
            Self::Glob { pattern, message } => {
                write!(f, "member pattern {pattern:?}: {message}")
            }
            Self::NoPackage => write!(
                f,
                "no package or workspace found: expected a Cargo.toml with [package]/[workspace] \
                 or a package.json at the repository root"
            ),
            Self::Duplicate {
                name,
                first,
                second,
            } => write!(
                f,
                "duplicate package name {name:?} in one ecosystem: {first} and {second}"
            ),
            Self::UnknownLink { name } => {
                write!(f, "explicit [[link]] names unknown package {name:?}")
            }
        }
    }
}

impl std::error::Error for DiscoverError {}

/// The per-ecosystem discovery seam (§7.3, discovery subset).
///
/// `edit_versions`, `patch_lockfile`, `publish` and the other §7.3 methods
/// are **intentionally absent** until the mutation/publish engines exist
/// (M3/M5): a trait method that is not implemented end-to-end would be a
/// stub, and stubs are forbidden (TASK §2.2). The trait is extended in the
/// slice that implements the method for real — see `PROGRESS.md`, slice C.
pub trait EcosystemAdapter: Send + Sync {
    /// Adapter identifier (`cargo`, `npm`), used in logs and diagnostics.
    fn id(&self) -> &'static str;
    /// Identify member manifests from the orchestrator-provided tree and
    /// produce raw package rows. Pure parse: no process spawn, no I/O.
    fn discover(&self, ctx: &DiscoverCtx) -> Result<Vec<RawPackage>, DiscoverError>;
}

/// Merge-time context: links a [`RawPackage`]/[`RawDep`] name to the
/// interned forms the [`Workspace`](crate::package::Workspace) stores.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ResolvedDep {
    /// Target package id.
    pub to: PkgId,
    /// Interned dependency name.
    pub name: Sym,
    /// Edge kind.
    pub kind: DepKind,
    /// Requirement as written.
    pub req: ReqSpec,
    /// Where the requirement text lives.
    pub site: ManifestSite,
}

#[cfg(test)]
mod tests {
    use super::*;

    fn ctx_with(files: &[(&str, &str)]) -> DiscoverCtx {
        let mut ctx = DiscoverCtx::new();
        for (path, body) in files {
            assert!(ctx.insert_file(path, body.as_bytes().to_vec()), "{path}");
        }
        ctx
    }

    #[test]
    fn ctx_inventory_and_contents() {
        let ctx = ctx_with(&[
            ("Cargo.toml", "[workspace]\nmembers = [\"a\"]\n"),
            ("a/Cargo.toml", "[package]\nname = \"a\"\n"),
            ("docs/readme.md", "hi\n"),
        ]);
        assert_eq!(ctx.file("Cargo.toml").map(|b| b.len()), Some(30));
        assert!(ctx.file("a/Cargo.toml").is_some());
        assert!(ctx.file("missing").is_none());
        let tomls = ctx.files_with_suffix("Cargo.toml");
        assert_eq!(tomls, vec!["Cargo.toml", "a/Cargo.toml"]);
        let dirs = ctx.dirs();
        assert_eq!(dirs, vec!["a", "docs"]);
    }

    #[test]
    fn ctx_rejects_non_normalized_paths() {
        let mut ctx = DiscoverCtx::new();
        assert!(!ctx.insert_file("/abs", b"x".to_vec()));
        assert!(!ctx.insert_file("a/../b", b"x".to_vec()));
        assert!(!ctx.insert_file("", b"x".to_vec()));
        assert!(ctx.insert_file("ok.txt", b"x".to_vec()));
    }

    #[test]
    fn insert_order_does_not_change_iteration() {
        let mut a = DiscoverCtx::new();
        let mut b = DiscoverCtx::new();
        for (path, body) in [("z.txt", "1"), ("a.txt", "2"), ("m/x.txt", "3")] {
            a.insert_file(path, body.as_bytes().to_vec());
        }
        for (path, body) in [("m/x.txt", "3"), ("z.txt", "1"), ("a.txt", "2")] {
            b.insert_file(path, body.as_bytes().to_vec());
        }
        assert_eq!(a.tree().collect::<Vec<_>>(), b.tree().collect::<Vec<_>>());
    }

    #[test]
    fn error_codes_are_stable() {
        let e = DiscoverError::NoPackage;
        assert_eq!(e.code(), "E-DISC-NO-PACKAGE");
        let e = DiscoverError::NestedWorkspace {
            outer: "Cargo.toml".into(),
            inner: "sub/Cargo.toml".into(),
        };
        assert_eq!(e.code(), "E-DISC-NESTED-WS");
        assert!(e.to_string().contains("nested workspace"));
    }
}
