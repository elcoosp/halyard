//! Package, dependency-edge and workspace types (§5.3, §6.6), plus the tag
//! template grammar (appendix A.3).
//!
//! This module is the discovery output contract: adapters (M1.5/M1.6)
//! produce a [`Workspace`]; the graph enrichment (CSR adjacency, topo
//! order, SCCs, polyglot links) is layered on by M1.7.

use bstr::BString;
use semver::Version;

use crate::id::{Interner, PkgId, Sym};

/// Package ecosystem (§5.2). Open set: built-ins plus adapter-registered
/// `Custom` symbols. `#[non_exhaustive]`: new built-ins require an ADR.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub enum Ecosystem {
    /// Rust / crates.io (`Cargo.toml`).
    Cargo,
    /// npm / pnpm / yarn / bun (`package.json` family, §6.4).
    Npm,
    /// Adapter-defined ecosystem; the symbol resolves through the
    /// workspace [`Interner`].
    Custom(Sym),
}

impl Ecosystem {
    /// Stable identifier used in plans and tag templates: `cargo`, `npm`,
    /// or the interner-resolved custom name (`custom` for a foreign
    /// symbol).
    pub fn resolve<'a>(&self, interner: &'a Interner) -> &'a str {
        match self {
            Self::Cargo => "cargo",
            Self::Npm => "npm",
            Self::Custom(sym) => interner.get(*sym).unwrap_or("custom"),
        }
    }
}

/// Repo-relative, forward-slash, UTF-8 path (§5.3): no leading `/`, no
/// empty components, no `.`/`..` components, no backslashes.
#[derive(Clone, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct RelPath(String);

impl RelPath {
    /// Validates and constructs; `None` when `raw` is not a normalized
    /// repo-relative path.
    pub fn new(raw: &str) -> Option<Self> {
        if raw.is_empty() || raw.starts_with('/') || raw.contains('\\') {
            return None;
        }
        let bad_component = raw
            .split('/')
            .any(|c| c.is_empty() || c == "." || c == "..");
        if bad_component {
            return None;
        }
        Some(Self(raw.to_owned()))
    }

    /// Path text (forward slashes).
    pub fn as_str(&self) -> &str {
        &self.0
    }

    /// Joins a validated relative suffix (invariant-preserving: both parts
    /// are already normalized).
    #[must_use]
    pub fn join(&self, suffix: &RelPath) -> RelPath {
        RelPath(format!("{}/{}", self.0, suffix.0))
    }

    /// Last path segment (`Cargo.toml` for `crates/core/Cargo.toml`).
    pub fn file_name(&self) -> &str {
        self.0.rsplit('/').next().unwrap_or_default()
    }

    /// Host path for filesystem effects (edits, reads).
    pub fn to_path_buf(&self) -> std::path::PathBuf {
        std::path::PathBuf::from(&self.0)
    }
}

impl std::fmt::Display for RelPath {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.0)
    }
}

impl std::fmt::Debug for RelPath {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        // Deterministic rendering (snapshot output): the plain path text.
        f.write_str(&self.0)
    }
}

/// Where a package's version comes from (§5.3).
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum VersionSource {
    /// Written in the package's own manifest.
    Local,
    /// Inherited from the workspace (`version.workspace = true`): edits go
    /// to the workspace manifest once and all inheritors form one lockstep
    /// unit (§6.3).
    WorkspaceInherited {
        /// Manifest carrying the authoritative version.
        file: RelPath,
        /// Key path inside that manifest (e.g. `package.version`).
        key_path: BString,
    },
    /// Generated by a tool; not editable in place.
    Dynamic,
}

/// Dependency edge kind (§5.3).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum DepKind {
    /// `[dependencies]`.
    Normal,
    /// `[build-dependencies]`.
    Build,
    /// `[dev-dependencies]` (never forces cascades by default, §6.3).
    Dev,
    /// npm `peerDependencies`.
    Peer,
    /// An optional dependency (`optional = true` / `optionalDependencies`).
    Optional,
}

impl DepKind {
    /// Wire keyword used by `halyard-plan/v1` cascade reasons.
    pub const fn wire_key(self) -> &'static str {
        match self {
            Self::Normal => "normal",
            Self::Build => "build",
            Self::Dev => "dev",
            Self::Peer => "peer",
            Self::Optional => "optional",
        }
    }
}

/// npm `workspace:` protocol shape (§6.4).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum WorkspaceProtocol {
    /// `workspace:*`.
    Star,
    /// `workspace:^`.
    Caret,
    /// `workspace:~`.
    Tilde,
    /// `workspace:1.2.3` (explicit version).
    Exact,
}

/// A dependency requirement as written in a manifest (§5.3
/// `DepEdge.req`). The requirement's edit site is recorded separately in
/// [`ManifestSite`].
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum ReqSpec {
    /// A semver requirement string (cargo-style ranges).
    VersionReq(semver::VersionReq),
    /// `workspace:*` / `workspace:^` / `workspace:~` / `workspace:1.2.3`.
    WorkspaceProtocol(WorkspaceProtocol),
    /// pnpm `catalog:` (default catalog) or `catalog:<name>` (§6.4).
    Catalog(Option<BString>),
    /// A path dependency with no version requirement.
    PathOnly,
}

/// Byte range within a manifest file (§5.3 edit sites, §9.1 patches).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Span {
    /// Inclusive start byte offset.
    pub start: u32,
    /// Exclusive end byte offset.
    pub end: u32,
}

/// Where a requirement is written: one manifest file plus the byte span(s)
/// carrying the requirement text (the patch target, §9.1).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ManifestSite {
    /// Manifest carrying the requirement.
    pub file: RelPath,
    /// Byte spans of the requirement text (ordered, non-overlapping).
    pub spans: Vec<Span>,
}

/// include/exclude globs deciding which changed paths count towards a
/// package (§5.3, §8.4). Pattern *matching* lands with the tree-diff stage
/// (M2.3); this type is the shared data carrier for adapters and config.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct PathFilter {
    include: Vec<BString>,
    exclude: Vec<BString>,
}

impl PathFilter {
    /// Builds a filter from include/exclude glob strings (empty include
    /// list = "everything counts" until the walk stage refines it).
    pub fn new(include: Vec<String>, exclude: Vec<String>) -> Self {
        Self {
            include: include.into_iter().map(BString::from).collect(),
            exclude: exclude.into_iter().map(BString::from).collect(),
        }
    }

    /// Include globs (empty = unrestricted).
    pub fn include(&self) -> &[BString] {
        &self.include
    }

    /// Exclude globs.
    pub fn exclude(&self) -> &[BString] {
        &self.exclude
    }

    /// True when both lists are empty.
    pub fn is_empty(&self) -> bool {
        self.include.is_empty() && self.exclude.is_empty()
    }
}

/// Errors from [`TagTemplate::parse`] (appendix A.3 grammar). Surfaced to
/// users as `E-CFG-TAG-STYLE` through the config loader (M1.8).
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum TagTemplateError {
    /// The template contains a nested `{` inside a placeholder.
    UnclosedBrace,
    /// A placeholder token is not one of the supported names.
    UnknownPlaceholder {
        /// The offending token (without braces).
        token: String,
    },
    /// The template carries no `{version}` placeholder, so no version can
    /// be extracted from rendered tags.
    MissingVersionPlaceholder,
    /// A placeholder token appears more than once.
    DuplicatePlaceholder {
        /// The duplicated token.
        token: String,
    },
    /// The template is empty.
    Empty,
}

impl std::fmt::Display for TagTemplateError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::UnclosedBrace => {
                write!(f, "template has a nested or unterminated `{{`")
            }
            Self::UnknownPlaceholder { token } => write!(
                f,
                "unknown placeholder `{{{token}}}` (supported: name, version, major, minor, \
                 patch, ecosystem)"
            ),
            Self::MissingVersionPlaceholder => {
                write!(f, "template must contain a `{{version}}` placeholder")
            }
            Self::DuplicatePlaceholder { token } => {
                write!(f, "placeholder `{{{token}}}` appears more than once")
            }
            Self::Empty => write!(f, "template is empty"),
        }
    }
}

impl std::error::Error for TagTemplateError {}

/// Tag naming template (appendix A.3): literal text plus the placeholders
/// `{name}`, `{version}`, `{major}`, `{minor}`, `{patch}`, `{ecosystem}`.
/// Defaults: `v{version}` for single-package mode, `{name}-v{version}` for
/// independent packages.
///
/// The literal `auto` style is resolved by the config layer (M1.8) before a
/// template is constructed; [`TagTemplate::parse`] rejects it via
/// [`TagTemplateError::MissingVersionPlaceholder`].
#[derive(Clone, Debug, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub struct TagTemplate(String);

impl TagTemplate {
    /// Supported placeholder tokens.
    const SUPPORTED: &'static [&'static str] =
        &["name", "version", "major", "minor", "patch", "ecosystem"];

    /// Parses and validates a template string.
    pub fn parse(raw: &str) -> Result<Self, TagTemplateError> {
        if raw.is_empty() {
            return Err(TagTemplateError::Empty);
        }
        let bytes = raw.as_bytes();
        let mut seen: Vec<&str> = Vec::new();
        let mut i = 0usize;
        while i < bytes.len() {
            if bytes.get(i) == Some(&b'{') {
                let close = (i + 1..bytes.len()).find(|off| bytes.get(*off) == Some(&b'}'));
                let close = close.ok_or(TagTemplateError::UnclosedBrace)?;
                let token = raw
                    .get(i + 1..close)
                    .ok_or(TagTemplateError::UnclosedBrace)?;
                if !Self::SUPPORTED.contains(&token) {
                    return Err(TagTemplateError::UnknownPlaceholder {
                        token: token.to_owned(),
                    });
                }
                if seen.contains(&token) {
                    return Err(TagTemplateError::DuplicatePlaceholder {
                        token: token.to_owned(),
                    });
                }
                seen.push(token);
                i = close + 1;
            } else {
                i += 1;
            }
        }
        if !seen.contains(&"version") {
            return Err(TagTemplateError::MissingVersionPlaceholder);
        }
        Ok(Self(raw.to_owned()))
    }

    /// Template text.
    pub fn as_str(&self) -> &str {
        &self.0
    }

    /// Renders the template for one release (appendix A.3).
    pub fn render(&self, name: &str, version: &Version, ecosystem: &str) -> String {
        render_with_version(self.0.as_str(), name, version, ecosystem)
    }

    /// Extracts the version out of a rendered tag for this template:
    /// `extract_version("core-v0.5.0", "core", "cargo")` on the
    /// `{name}-v{version}` template yields `0.5.0`.
    ///
    /// `{major}`/`{minor}`/`{patch}` placeholders outside `{version}` pin
    /// literal version components and are not supported for extraction
    /// (`None`); extraction covers the §8.2 shapes (`v{version}`,
    /// `{name}-v{version}`, scoped npm names).
    pub fn extract_version(&self, tag: &str, name: &str, ecosystem: &str) -> Option<Version> {
        let raw = self.0.as_str();
        let open = raw.find("{version}")?;
        let prefix_tpl = raw.get(..open)?;
        let suffix_tpl = raw.get(open + "{version}".len()..).unwrap_or_default();
        let prefix = render_static(prefix_tpl, name, ecosystem);
        let suffix = render_static(suffix_tpl, name, ecosystem);
        if prefix.contains('{') || suffix.contains('{') {
            return None;
        }
        if !tag.starts_with(&prefix) || !tag.ends_with(&suffix) {
            return None;
        }
        let middle_len = tag.len().checked_sub(prefix.len() + suffix.len())?;
        let middle = tag.get(prefix.len()..prefix.len() + middle_len)?;
        Version::parse(middle).ok()
    }
}

/// Renders placeholders that carry a concrete version.
fn render_with_version(template: &str, name: &str, version: &Version, ecosystem: &str) -> String {
    let bytes = template.as_bytes();
    let mut out = String::with_capacity(template.len() + 8);
    let mut i = 0usize;
    while i < bytes.len() {
        if bytes.get(i) == Some(&b'{') {
            let close = (i + 1..bytes.len()).find(|off| bytes.get(*off) == Some(&b'}'));
            if let Some(close) = close {
                let token = template.get(i + 1..close).unwrap_or_default();
                match token {
                    "name" => out.push_str(name),
                    "version" => out.push_str(&version.to_string()),
                    "major" => out.push_str(&version.major.to_string()),
                    "minor" => out.push_str(&version.minor.to_string()),
                    "patch" => out.push_str(&version.patch.to_string()),
                    "ecosystem" => out.push_str(ecosystem),
                    _ => {}
                }
                i = close + 1;
                continue;
            }
        }
        let ch_len = template
            .get(i..)
            .and_then(|s| s.chars().next())
            .map_or(1, char::len_utf8);
        if let Some(chunk) = template.get(i..i + ch_len) {
            out.push_str(chunk);
        }
        i += ch_len;
    }
    out
}

/// Renders only `{name}`/`{ecosystem}`; other placeholders pass through
/// untouched (used by [`TagTemplate::extract_version`]).
fn render_static(template: &str, name: &str, ecosystem: &str) -> String {
    let bytes = template.as_bytes();
    let mut out = String::with_capacity(template.len());
    let mut i = 0usize;
    while i < bytes.len() {
        if bytes.get(i) == Some(&b'{') {
            let close = (i + 1..bytes.len()).find(|off| bytes.get(*off) == Some(&b'}'));
            if let Some(close) = close {
                let token = template.get(i + 1..close).unwrap_or_default();
                match token {
                    "name" => out.push_str(name),
                    "ecosystem" => out.push_str(ecosystem),
                    other => {
                        out.push('{');
                        out.push_str(other);
                        out.push('}');
                    }
                }
                i = close + 1;
                continue;
            }
        }
        let ch_len = template
            .get(i..)
            .and_then(|s| s.chars().next())
            .map_or(1, char::len_utf8);
        if let Some(chunk) = template.get(i..i + ch_len) {
            out.push_str(chunk);
        }
        i += ch_len;
    }
    out
}

/// Dense index into [`Workspace::groups`].
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct GroupId(u32);

impl GroupId {
    /// Wraps a raw index.
    pub const fn new(raw: u32) -> Self {
        Self(raw)
    }

    /// Raw index value.
    pub const fn to_u32(self) -> u32 {
        self.0
    }
}

/// Versioning policy for a group (§5.4).
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum GroupPolicy {
    /// Every package versions on its own (default).
    #[default]
    Independent,
    /// All members share one version.
    Fixed,
    /// Members move together at the same bump level.
    Linked,
}

/// A versioning-policy unit (§5.4), carrying the tag template used by its
/// members (`v{version}` for fixed, `{name}-v{version}` for independent).
#[derive(Clone, Debug)]
pub struct Group {
    /// Group id.
    pub id: GroupId,
    /// Group name (interned).
    pub name: Sym,
    /// Versioning policy.
    pub policy: GroupPolicy,
    /// Member packages.
    pub members: Vec<PkgId>,
    /// Tag template rendered for this group's releases.
    pub tag_template: TagTemplate,
}

/// One discovered package (§5.3).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Package {
    /// Dense id (== index in [`Workspace::packages`]).
    pub id: PkgId,
    /// Package name (crate name or npm name), interned.
    pub name: Sym,
    /// Ecosystem.
    pub ecosystem: Ecosystem,
    /// Package root directory, relative to the repo root.
    pub root: RelPath,
    /// Manifest path (e.g. `crates/a/Cargo.toml`).
    pub manifest: RelPath,
    /// Current version in the manifest (`None` for packages without a
    /// version — unpublishable, warn, §6.3).
    pub version: Option<Version>,
    /// Where the version comes from.
    pub version_source: VersionSource,
    /// Whether the package may be published (`publish = false` /
    /// `private: true` flip this off, §6.3/§6.4).
    pub publishable: bool,
    /// Outgoing edges to workspace members only.
    pub deps: Vec<DepEdge>,
    /// Tag template rendered for this package's releases.
    pub tag_template: TagTemplate,
    /// Changelog file, when the package owns one.
    pub changelog: Option<RelPath>,
    /// Which files count as "changes to this package".
    pub include: PathFilter,
    /// Versioning group this package belongs to.
    pub group: GroupId,
}

/// One dependency edge to a workspace member (§5.3).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct DepEdge {
    /// Target package.
    pub to: PkgId,
    /// Edge kind.
    pub kind: DepKind,
    /// Requirement as written.
    pub req: ReqSpec,
    /// Where the requirement text lives (the edit site, §9.1).
    pub site: ManifestSite,
}

/// The discovered monorepo (§6.6): packages, groups and the shared
/// interner. Graph fields (CSR in/out adjacency, topo order, SCCs) and the
/// path trie arrive with M1.7; this type is the discovery contract they
/// build on.
#[derive(Clone, Debug, Default)]
pub struct Workspace {
    interner: Interner,
    packages: Vec<Package>,
    groups: Vec<Group>,
}

impl Workspace {
    /// Empty workspace.
    pub fn new() -> Self {
        Self::default()
    }

    /// Interns a name in the workspace interner.
    pub fn intern(&mut self, s: &str) -> Sym {
        self.interner.intern(s)
    }

    /// Shared interner.
    pub fn interner(&self) -> &Interner {
        &self.interner
    }

    /// Registers `package` and assigns its id; the passed id field is
    /// overwritten with the assigned value.
    pub fn push_package(&mut self, mut package: Package) -> PkgId {
        let id = PkgId::new(u32::try_from(self.packages.len()).unwrap_or(u32::MAX));
        package.id = id;
        self.packages.push(package);
        id
    }

    /// All packages in registration (discovery) order.
    pub fn packages(&self) -> &[Package] {
        &self.packages
    }

    /// Package by id (`None` for a foreign id).
    pub fn package(&self, id: PkgId) -> Option<&Package> {
        self.packages.get(id.to_usize())
    }

    /// Adds a group; returns its id.
    pub fn add_group(
        &mut self,
        name: Sym,
        policy: GroupPolicy,
        members: Vec<PkgId>,
        tag_template: TagTemplate,
    ) -> GroupId {
        let id = GroupId::new(u32::try_from(self.groups.len()).unwrap_or(u32::MAX));
        self.groups.push(Group {
            id,
            name,
            policy,
            members,
            tag_template,
        });
        id
    }

    /// All groups.
    pub fn groups(&self) -> &[Group] {
        &self.groups
    }

    /// Group by id (`None` for a foreign id).
    pub fn group(&self, id: GroupId) -> Option<&Group> {
        self.groups.get(id.to_u32() as usize)
    }

    /// Finds a package by name (exact match on interned names).
    pub fn find_by_name(&self, name: &str) -> Option<PkgId> {
        self.packages
            .iter()
            .find(|p| self.interner.get(p.name) == Some(name))
            .map(|p| p.id)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rel_path_validation() {
        assert!(RelPath::new("crates/core/Cargo.toml").is_some());
        assert!(RelPath::new("Cargo.toml").is_some());
        assert!(RelPath::new("/abs").is_none());
        assert!(RelPath::new("").is_none());
        assert!(RelPath::new("a//b").is_none());
        assert!(RelPath::new("a/../b").is_none());
        assert!(RelPath::new("./a").is_none());
        assert!(RelPath::new("a\\b").is_none());
        let root = RelPath::new("crates/core").unwrap();
        let file = RelPath::new("Cargo.toml").unwrap();
        assert_eq!(root.join(&file).as_str(), "crates/core/Cargo.toml");
        assert_eq!(root.file_name(), "core");
    }

    #[test]
    fn tag_template_roundtrip_and_extraction() {
        let tpl = TagTemplate::parse("{name}-v{version}").unwrap();
        let v = Version::parse("0.5.0").unwrap();
        assert_eq!(tpl.render("core", &v, "cargo"), "core-v0.5.0");
        assert_eq!(
            tpl.extract_version("core-v0.5.0", "core", "cargo"),
            Some(v.clone())
        );
        assert_eq!(tpl.extract_version("other-v0.5.0", "core", "cargo"), None);
        let scoped = TagTemplate::parse("@scope/{name}@{version}").unwrap();
        assert_eq!(
            scoped
                .extract_version("@scope/cli@1.2.3", "cli", "npm")
                .map(|v| v.to_string()),
            Some("1.2.3".to_owned())
        );
        let bare = TagTemplate::parse("v{version}").unwrap();
        assert_eq!(bare.render("anything", &v, "cargo"), "v0.5.0");
    }

    #[test]
    fn tag_template_errors() {
        assert!(matches!(
            TagTemplate::parse(""),
            Err(TagTemplateError::Empty)
        ));
        assert!(matches!(
            TagTemplate::parse("{version"),
            Err(TagTemplateError::UnclosedBrace)
        ));
        assert!(matches!(
            TagTemplate::parse("{naame}"),
            Err(TagTemplateError::UnknownPlaceholder { .. })
        ));
        assert!(matches!(
            TagTemplate::parse("release"),
            Err(TagTemplateError::MissingVersionPlaceholder)
        ));
        assert!(matches!(
            TagTemplate::parse("{version}-{version}"),
            Err(TagTemplateError::DuplicatePlaceholder { .. })
        ));
    }

    #[test]
    fn workspace_registration_and_lookup() {
        let mut ws = Workspace::new();
        let name = ws.intern("core");
        let pkg = Package {
            id: PkgId::FIRST,
            name,
            ecosystem: Ecosystem::Cargo,
            root: RelPath::new("crates/core").unwrap(),
            manifest: RelPath::new("crates/core/Cargo.toml").unwrap(),
            version: Some(Version::parse("0.4.1").unwrap()),
            version_source: VersionSource::Local,
            publishable: true,
            deps: Vec::new(),
            tag_template: TagTemplate::parse("{name}-v{version}").unwrap(),
            changelog: None,
            include: PathFilter::new(Vec::new(), Vec::new()),
            group: GroupId::new(0),
        };
        let id = ws.push_package(pkg);
        assert_eq!(id, PkgId::new(0));
        assert_eq!(ws.find_by_name("core"), Some(id));
        assert_eq!(ws.package(id).map(|p| p.publishable), Some(true));
        assert_eq!(ws.package(PkgId::new(9)), None);
        let gid = ws.add_group(
            name,
            GroupPolicy::Fixed,
            vec![id],
            TagTemplate::parse("v{version}").unwrap(),
        );
        assert_eq!(ws.group(gid).map(|g| g.policy), Some(GroupPolicy::Fixed));
        assert_eq!(Ecosystem::Cargo.resolve(ws.interner()), "cargo");
    }
}
