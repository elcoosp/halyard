//! Example: patch a Cargo.lock for the plan's version moves (M3.2).
//!
//! Run: `cargo run -p halyard-eco-cargo --example patch_lockfile`
//!
//! Demonstrates the §9.2 lockfile seam: the planned version moves drive
//! the rewrite of workspace-member `version` rows and `"name version"`
//! dependency entries, byte-in place (invariant I4). Anything the patcher
//! cannot guarantee cargo-identical bytes for comes back as
//! `NeedsNative` (§9.2 rule 4) instead of a guess.

use halyard_core::lockfile::{LockfileOutcome, LockfileVersionChange};
use halyard_eco_cargo::lockfile::patch_lockfile;

const LOCKFILE: &str = r#"# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "app"
version = "0.4.1"
dependencies = [
 "engine",
]

[[package]]
name = "engine"
version = "0.4.1"

[[package]]
name = "tools"
version = "2.1.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "5af1a99ffa2c9bb3a04eaa9a24b6b8f9d2f0f05c65a02a4a11cd93a26a11b6c0"
dependencies = [
 "engine 0.4.1 registry+https://github.com/rust-lang/crates.io-index",
]
"#;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let changes = [
        LockfileVersionChange {
            name: "app".to_owned(),
            from: "0.4.1".to_owned(),
            to: "0.5.0".to_owned(),
        },
        LockfileVersionChange {
            name: "engine".to_owned(),
            from: "0.4.1".to_owned(),
            to: "0.5.0".to_owned(),
        },
    ];
    let outcome = patch_lockfile(LOCKFILE, "Cargo.lock", &changes)?;
    match outcome {
        LockfileOutcome::Patched {
            content,
            applied,
            skipped,
        } => {
            let text = String::from_utf8(content)?;
            println!("patched: {applied} applied, {skipped} skipped\n");
            println!("{text}");
        }
        LockfileOutcome::NeedsNative { reason } => {
            println!("needs native refresh: {reason}");
        }
    }
    Ok(())
}
