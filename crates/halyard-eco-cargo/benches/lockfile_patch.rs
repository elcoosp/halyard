//! Bench: Cargo.lock patch pass (M3.2, §9.2 hot path of the apply flow).
//!
//! Measures the full `patch_lockfile` walk (parse + member-row and
//! dependency-entry matching + byte rewrite + read-back verification)
//! over a synthetic 120-package lockfile where 40 members are bumped
//! together with their disambiguated dependency entries. Formal apply
//! budgets are §14.1 ("Apply edits (40 files)"); the lockfile pass is
//! part of that stage.

use criterion::Criterion;
use halyard_core::lockfile::LockfileVersionChange;
use halyard_eco_cargo::lockfile::{patch_lockfile, verify_native_refresh};

/// Builds a deterministic synthetic lockfile: `members` source-less
/// workspace rows plus `registry` rows that reference the members in the
/// disambiguated `"name version"` form (§9.2 rule 2). Every entry carries
/// the referenced package's exact version — a mismatched token would make
/// the patcher correctly decline as drift.
fn synthetic_lock(members: usize, registry: usize) -> String {
    use std::fmt::Write as _;
    let mut out = String::from(
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual \
         editing.\nversion = 4\n\n",
    );
    for i in 0..members {
        let _ = writeln!(
            out,
            "[[package]]\nname = \"member-{i:04}\"\nversion = \"0.1.{}\"\ndependencies = [\n \
             \"member-{:04} 0.1.{}\",\n \"member-{:04}\",\n]\n",
            i % 10,
            (i + 1) % members.max(1),
            // The referenced member's exact version (its `from`).
            ((i + 1) % members.max(1)) % 10,
            (i + 2) % members.max(1),
        );
    }
    for r in 0..registry {
        let _ = writeln!(
            out,
            "[[package]]\nname = \"registry-{r:04}\"\nversion = \"1.0.{}\"\nsource = \
             \"registry+https://github.com/rust-lang/crates.io-index\"\nchecksum = \
             \"{r:064x}\"\ndependencies = [\n \"member-{:04} 0.1.{}\",\n \"registry-{:04} \
             1.0.{} registry+https://github.com/rust-lang/crates.io-index\",\n]\n",
            r % 10,
            r % members.max(1),
            (r % members.max(1)) % 10,
            (r + 1) % registry.max(1),
            (r + 1) % 10,
        );
    }
    out
}

/// The planned moves: every member moves `0.1.N` → `0.2.N` (all 40 in the
/// bench's fixture, so member rows and their disambiguated entries both
/// rewrite).
fn changes_for(members: usize) -> Vec<LockfileVersionChange> {
    (0..members)
        .map(|i| LockfileVersionChange {
            name: format!("member-{i:04}"),
            from: format!("0.1.{}", i % 10),
            to: format!("0.2.{}", i % 10),
        })
        .collect()
}

fn bench_lockfile_patch(c: &mut Criterion) {
    let lock = synthetic_lock(40, 80);
    let changes = changes_for(40);
    let mut group = c.benchmark_group("eco-cargo");
    group.throughput(criterion::Throughput::Bytes(
        u64::try_from(lock.len()).unwrap_or(u64::MAX),
    ));
    group.bench_function("patch_lockfile_120pkg_40moves", |b| {
        b.iter(
            || match patch_lockfile(std::hint::black_box(&lock), "Cargo.lock", &changes) {
                Ok(outcome) => outcome,
                Err(e) => unreachable!("fixture patches cleanly: {e}"),
            },
        );
    });
    // M2 companion: the post-refresh verification gate
    // (`verify_native_refresh`) walks the same row/entry space over the
    // before/after pair — its cost is what the native fallback adds on
    // top of the spawn.
    let patched = match patch_lockfile(&lock, "Cargo.lock", &changes) {
        Ok(halyard_core::lockfile::LockfileOutcome::Patched { content, .. }) => content,
        other => unreachable!("fixture patches cleanly: {other:?}"),
    };
    let members: Vec<String> = (0..40usize).map(|i| format!("member-{i:04}")).collect();
    group.bench_function("verify_native_refresh_120pkg_40moves", |b| {
        b.iter(|| {
            match verify_native_refresh(
                std::hint::black_box(lock.as_bytes()),
                std::hint::black_box(&patched),
                &members,
            ) {
                Ok(moved) => moved,
                Err(e) => unreachable!("fixture verifies cleanly: {e}"),
            }
        });
    });
    group.finish();
}

/// Criterion harness entry (the `criterion_group!` expansion, spelled out
/// so the generated `pub fn` does not trip `missing_docs`).
fn benches() {
    let mut criterion: Criterion = Criterion::default().configure_from_args();
    bench_lockfile_patch(&mut criterion);
}

fn main() {
    benches();
    Criterion::default().configure_from_args().final_summary();
}
