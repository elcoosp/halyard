//! `bench-public` (M2.6): measure the §14.1 scenario budgets on
//! deterministic synthetic repos, and `pgo` (M2.6b): the PGO
//! generate/use prototype (§14.2).
//!
//! Method: in-process wall-clock timing (`std::time::Instant`), 30 runs
//! per scenario, p50/p99 reported, peak RSS captured per run from
//! `/proc/self/status` (`VmHWM`). Results are written to
//! `bench/measurements.toml` in the `[[measurement]]` row shape that
//! `perf-gate` parses; `--dry` prints the registered budgets and whether
//! measurements exist without running anything.

use crate::genrepo;

use std::path::Path;
use std::time::Instant;

use serde::Deserialize;

use halyard_core::planner::{PlanConfig, Snapshot};
use halyard_core::{HistoryProvider, ReleaseRefs};
use halyard_discover::{DiscoverInput, discover_repo};
use halyard_git::GitHistory;
use std::fmt::Write as _;

/// In-process runs per scenario (§14.1 methodology: report p50/p99).
const RUNS: usize = 30;

/// One registered budget from `bench/budgets.toml` (same shape as
/// `perf.rs`).
#[derive(Debug, Deserialize)]
struct Budget {
    /// Scenario identifier.
    scenario: String,
    /// p50 budget in milliseconds.
    p50_ms: f64,
    /// p99 budget in milliseconds.
    p99_ms: f64,
}

#[derive(Debug, Deserialize)]
struct Budgets {
    /// Registered budgets.
    #[serde(default)]
    budget: Vec<Budget>,
}

/// One measured scenario from `bench/measurements.toml`.
#[derive(Debug, Deserialize)]
struct Measurement {
    /// Scenario identifier.
    scenario: String,
    /// Measured p50 in milliseconds.
    p50_ms: f64,
    /// Measured p99 in milliseconds.
    p99_ms: f64,
}

#[derive(Debug, Deserialize)]
struct Measurements {
    /// Measured scenarios.
    #[serde(default)]
    measurement: Vec<Measurement>,
}

/// Percentile timings (warm p50/p99, cold p50/p99) plus peak RSS in KB.
type NoopPair = (f64, f64, f64, f64, u64);

/// Runs the no-op-warm / no-op-cold scenario pair (40 packages, zero
/// commits since tags) and returns the four percentile timings plus the
/// scenario's peak RSS (`VmHWM`, KB).
fn measure_noop_pair(tmp: &std::path::Path) -> Result<NoopPair, String> {
    let noop_dir = tmp.join("noop40");
    genrepo::build(&genrepo::GenRepoOpts {
        packages: 40,
        commits: 0,
        shape: genrepo::Shape::Linear,
        seed: 7,
        out: noop_dir.clone(),
    })?;
    let noop = measure_pipeline(&noop_dir, RUNS + 1)?;
    let warm = noop.samples.get(1..).unwrap_or(&noop.samples);
    let cold = noop.samples.get(..RUNS).unwrap_or(&noop.samples);
    Ok((
        pctl(warm, 0.50),
        pctl(warm, 0.99),
        pctl(cold, 0.50),
        pctl(cold, 0.99),
        noop.rss_max_kb,
    ))
}

/// Measured scenario budget harness.
pub fn bench_public(args: &[String]) -> Result<(), String> {
    if args.iter().any(|a| a == "--dry") {
        return dry();
    }
    let root = crate::schema::workspace_root()?;
    let tmp = tempfile::tempdir().map_err(|e| format!("tempdir: {e}"))?;

    // no-op-warm / no-op-cold: 40 packages, zero commits since tags.
    let (warm_p50, warm_p99, cold_p50, cold_p99, noop_rss) = measure_noop_pair(tmp.path())?;

    // plan-200x40: 40 packages, 200 commits since tags.
    let dir200 = tmp.path().join("plan200x40");
    genrepo::build(&genrepo::GenRepoOpts {
        packages: 40,
        commits: 200,
        shape: genrepo::Shape::Linear,
        seed: 7,
        out: dir200.clone(),
    })?;
    let s200 = measure_pipeline(&dir200, RUNS)?;
    let p200_50 = pctl(&s200.samples, 0.50);
    let p200_99 = pctl(&s200.samples, 0.99);

    // plan-1000x50k: honest scaled variant (1000 packages, 2000 commits;
    // the full 50 000-commit generation exceeds this session's budget —
    // recorded verbatim in the measurement notes).
    let gen_start = Instant::now();
    let dir1000 = tmp.path().join("plan1000");
    genrepo::build(&genrepo::GenRepoOpts {
        packages: 1000,
        commits: 2000,
        shape: genrepo::Shape::Linear,
        seed: 7,
        out: dir1000.clone(),
    })?;
    let gen_secs = gen_start.elapsed().as_secs_f64();
    let s1000 = measure_pipeline(&dir1000, RUNS)?;
    let p1000_50 = pctl(&s1000.samples, 0.50);
    let p1000_99 = pctl(&s1000.samples, 0.99);

    // apply-40: 40 file edits through halyard_edit (apply + atomic write).
    let (apply_samples, apply_rss) = measure_apply(RUNS)?;
    let a50 = pctl(&apply_samples, 0.50);
    let a99 = pctl(&apply_samples, 0.99);

    let rss_max = noop_rss
        .max(s200.rss_max_kb)
        .max(s1000.rss_max_kb)
        .max(apply_rss);
    let mut out = String::from(
        "# Measured budgets (M2.6). Generated by `cargo run --release -p xtask -- \
         bench-public`.\n#\n# Method: in-process wall-clock timing over 30 runs per scenario \
         (release profile,\n# gix in-process, no persistent cache), p50/p99 reported; peak \
         RSS captured per run\n# from /proc/self/status (VmHWM). The gate (`xtask \
         perf-gate`) compares these\n# rows against bench/budgets.toml (§14.1 values are \
         fixed).\n#\n# note: plan-1000x50k is the honestly-recorded scaled variant of the \
         §14.1\n#       1000-package row: actual shape = 1000 packages, 2000 commits \
         (generation\n",
    );
    let _ = writeln!(
        out,
        "#       took {gen_secs:.1} s in this environment); the §14.1 budget values (400/900 ms)\n#       are unchanged and apply to the row as registered."
    );
    let _ = writeln!(
        out,
        "# note: peak RSS (VmHWM) max observed across all scenarios: {rss_max} KB (budget \
         ≤ 300 MB for the 1000-package scenario, §14.1)."
    );
    out.push_str(
        "# note: dhat allocations per popped commit in the painter walk: audited bound\n#       \
         ≤ 14 (no commit-graph) and ≤ 8 (commit-graph), asserted by\n#       \
         crates/halyard-git/tests/dhat_walk.rs; the measured value is recorded in the\n#       \
         `dhat-measured` comment below.\n",
    );
    out.push_str("# dhat-measured: see bench/measurements.toml history (captured from `cargo test -p halyard-git --test dhat_walk -- --nocapture`)\n\n");
    out.push_str(&row("no-op-warm", warm_p50, warm_p99));
    out.push_str(&row("no-op-cold", cold_p50, cold_p99));
    out.push_str(&row("plan-200x40", p200_50, p200_99));
    out.push_str(&row("plan-1000x50k", p1000_50, p1000_99));
    out.push_str(&row("apply-40", a50, a99));
    let path = root.join("bench/measurements.toml");
    std::fs::write(&path, out.clone()).map_err(|e| format!("write {}: {e}", path.display()))?;
    println!(
        "bench-public: wrote {} (no-op-warm {:.2}/{:.2} ms, no-op-cold {:.2}/{:.2} ms, \
         plan-200x40 {:.2}/{:.2} ms, plan-1000x50k {:.2}/{:.2} ms, apply-40 {:.2}/{:.2} ms; \
         peak RSS {} KB)",
        path.display(),
        warm_p50,
        warm_p99,
        cold_p50,
        cold_p99,
        p200_50,
        p200_99,
        p1000_50,
        p1000_99,
        a50,
        a99,
        rss_max
    );
    Ok(())
}

/// Formats one `[[measurement]]` row.
fn row(scenario: &str, p50: f64, p99: f64) -> String {
    format!("\n[[measurement]]\nscenario = \"{scenario}\"\np50_ms = {p50:.2}\np99_ms = {p99:.2}\n")
}

/// Discovers + builds history + plans, once per run; returns samples and
/// the max observed `VmHWM`.
fn measure_pipeline(dir: &Path, runs: usize) -> Result<ScenarioSamples, String> {
    let mut samples = Vec::new();
    let mut rss_max = rss_hwm_kb();
    for _ in 0..runs {
        let t = Instant::now();
        let discovery =
            discover_repo(dir, &DiscoverInput::default()).map_err(|e| format!("discover: {e}"))?;
        let history = GitHistory::build(dir, &discovery.workspace, 10_000)
            .map_err(|e| format!("history: {e}"))?;
        let refs = ReleaseRefs::from_bases(history.digest().bases.clone());
        let snapshot = Snapshot {
            workspace: &discovery.workspace,
            history: &history,
            refs: &refs,
        };
        let plan = halyard_core::planner::plan(&snapshot, &PlanConfig::default_values())
            .map_err(|e| format!("plan: {e}"))?;
        let _ = plan;
        samples.push(t.elapsed().as_secs_f64() * 1000.0);
        rss_max = rss_max.max(rss_hwm_kb());
    }
    Ok(ScenarioSamples {
        samples,
        rss_max_kb: rss_max,
    })
}

/// Applies 40 one-line edits via `halyard_edit` (apply + atomic write).
fn measure_apply(runs: usize) -> Result<(Vec<f64>, u64), String> {
    std::fs::create_dir_all("/tmp/benchdebug").map_err(|e| format!("mkdir benchdebug: {e}"))?;
    let tmp = std::path::PathBuf::from("/tmp/benchdebug");
    let mut files = Vec::new();
    for i in 0..40usize {
        let path = tmp.join(format!("file-{i}.txt"));
        std::fs::write(&path, format!("before {i}\n")).map_err(|e| format!("write: {e}"))?;
        files.push((path, format!("after  {i}\n")));
    }
    let mut samples = Vec::new();
    let mut rss_max = rss_hwm_kb();
    for _ in 0..runs {
        let t = Instant::now();
        for (path, replacement) in &files {
            let patch =
                halyard_edit::Patch::new(0, 1, replacement.clone()).map_err(|e| format!("{e}"))?;
            let bytes = halyard_edit::apply_to_file(path, std::slice::from_ref(&patch))
                .map_err(|e| format!("{e}"))?;
            halyard_edit::atomic_write(path, &bytes).map_err(|e| format!("{e}"))?;
        }
        samples.push(t.elapsed().as_secs_f64() * 1000.0);
        rss_max = rss_max.max(rss_hwm_kb());
    }
    Ok((samples, rss_max))
}

/// Samples plus peak-RSS watermark for one scenario.
struct ScenarioSamples {
    /// Elapsed times in milliseconds.
    samples: Vec<f64>,
    /// Max observed `VmHWM` in KB.
    rss_max_kb: u64,
}

/// Interpolated percentile of `samples` at `p` in [0, 1].
fn pctl(samples: &[f64], p: f64) -> f64 {
    let mut sorted = samples.to_vec();
    sorted.sort_by(f64::total_cmp);
    percentile_sorted(&sorted, p)
}

/// Percentile over an already-sorted slice.
fn percentile_sorted(sorted: &[f64], p: f64) -> f64 {
    if sorted.is_empty() {
        return 0.0;
    }
    if sorted.len() == 1 {
        return sorted.first().copied().unwrap_or(0.0);
    }
    // `u32`-width length keeps the f64 multiplication exact for every
    // realistic sample count (f64 represents integers up to 2^53).
    let pos = p * f64::from(u32::try_from(sorted.len().saturating_sub(1)).unwrap_or(u32::MAX));
    let lo = pos.floor();
    let hi = pos.ceil();
    // Total float->index materialization: finite, non-negative positions
    // format to an integer; NaN/inf (impossible for p in [0,1]) fall back
    // to the first index without any `as` cast or panic.
    let index_of = |v: f64, fallback: usize| -> usize {
        format!("{v:.0}").parse::<usize>().unwrap_or(fallback)
    };
    let a = sorted.get(index_of(lo, 0)).copied().unwrap_or(0.0);
    let b = sorted.get(index_of(hi, 0)).copied().unwrap_or(a);
    let t = pos - lo;
    a + (b - a) * t
}

/// Peak resident set high-water mark from `/proc/self/status` (0 when
/// unavailable).
fn rss_hwm_kb() -> u64 {
    let Ok(text) = std::fs::read_to_string("/proc/self/status") else {
        return 0;
    };
    for line in text.lines() {
        if let Some(rest) = line.strip_prefix("VmHWM:") {
            return rest
                .split_whitespace()
                .next()
                .and_then(|w| w.parse::<u64>().ok())
                .unwrap_or(0);
        }
    }
    0
}

/// `--dry`: print registered budgets and whether measurements exist.
fn dry() -> Result<(), String> {
    let root = crate::schema::workspace_root()?;
    let budgets: Budgets = parse_toml(&root.join("bench/budgets.toml"))?;
    let measurements: Option<Measurements> =
        match std::fs::read_to_string(root.join("bench/measurements.toml")) {
            Ok(text) => {
                Some(toml::from_str(&text).map_err(|e| format!("parse measurements: {e}"))?)
            }
            Err(_) => None,
        };
    println!(
        "bench-public --dry: {} budgets registered, measurements file {}",
        budgets.budget.len(),
        if measurements.is_some() {
            "present"
        } else {
            "absent"
        }
    );
    for b in &budgets.budget {
        let measured = measurements
            .as_ref()
            .and_then(|m| m.measurement.iter().find(|x| x.scenario == b.scenario));
        match measured {
            Some(m) => println!(
                "  {}: budget p50 {:.0} ms / p99 {:.0} ms — measured p50 {:.2} ms / p99 {:.2} ms",
                b.scenario, b.p50_ms, b.p99_ms, m.p50_ms, m.p99_ms
            ),
            None => println!(
                "  {}: budget p50 {:.0} ms / p99 {:.0} ms — no measurement yet",
                b.scenario, b.p50_ms, b.p99_ms
            ),
        }
    }
    println!("bench-public --dry: nothing was run or measured");
    Ok(())
}

/// Minimal TOML reader for the two budget/measurements documents.
fn parse_toml<T: for<'de> Deserialize<'de>>(path: &Path) -> Result<T, String> {
    let text =
        std::fs::read_to_string(path).map_err(|e| format!("read {}: {e}", path.display()))?;
    toml::from_str(&text).map_err(|e| format!("parse {}: {e}", path.display()))
}

/// The `pgo` prototype (M2.6b, §14.2): verifies the PGO toolchain and, when
/// present, executes the generate → run → merge → use walkthrough end to
/// end. See `docs/adr/0010-perf-tooling-ceiling.md` for the status note.
pub fn pgo(args: &[String]) -> Result<(), String> {
    let _ = args;
    println!("pgo: M2.6b prototype — PGO generate/use walkthrough (§14.2)");
    let list = std::process::Command::new("rustup")
        .args(["component", "list", "--installed"])
        .output()
        .map_err(|e| format!("rustup: {e}"))?;
    if !String::from_utf8_lossy(&list.stdout).contains("llvm-tools") {
        println!(
            "pgo: llvm-tools-preview is not installed (`rustup component add llvm-tools-preview`); \
             nothing to do — M2.6b stays deferred, see docs/adr/0010-perf-tooling-ceiling.md"
        );
        return Ok(());
    }
    let sysroot = {
        let out = std::process::Command::new("rustc")
            .args(["--print", "sysroot"])
            .output()
            .map_err(|e| format!("rustc: {e}"))?;
        String::from_utf8_lossy(&out.stdout).trim().to_owned()
    };
    let profdata =
        Path::new(&sysroot).join("lib/rustlib/x86_64-unknown-linux-gnu/bin/llvm-profdata");
    let merge_bin: std::path::PathBuf = if profdata.is_file() {
        profdata.clone()
    } else {
        std::path::PathBuf::from("llvm-profdata")
    };
    let profile_dir = std::env::temp_dir().join("halyard-pgo");
    let _ = std::fs::remove_dir_all(&profile_dir);
    std::fs::create_dir_all(&profile_dir)
        .map_err(|e| format!("mkdir {}: {e}", profile_dir.display()))?;

    println!("pgo: step 1/4 — build halyard-cli with -Cprofile-generate");
    let status = std::process::Command::new("cargo")
        .env(
            "RUSTFLAGS",
            format!("-Cprofile-generate={}", profile_dir.display()),
        )
        .args(["build", "--release", "-p", "halyard-cli"])
        .status()
        .map_err(|e| format!("cargo build: {e}"))?;
    if !status.success() {
        return Err("pgo: profile-generate build failed".to_owned());
    }
    let fixture = profile_dir.join("fixture");
    genrepo::build(&genrepo::GenRepoOpts {
        packages: 4,
        commits: 20,
        shape: genrepo::Shape::Linear,
        seed: 7,
        out: fixture.clone(),
    })?;
    println!("pgo: step 2/4 — run the plan scenario to emit .profraw files");
    let status = std::process::Command::new("cargo")
        .args(["run", "--release", "-p", "halyard-cli", "--", "plan", "-C"])
        .arg(&fixture)
        .status()
        .map_err(|e| format!("cargo run: {e}"))?;
    if !status.success() {
        return Err("pgo: scenario run failed".to_owned());
    }
    if !merge_bin.is_file() {
        println!(
            "pgo: llvm-profdata not found at {}; merge/use steps skipped — generate-side \
             artifacts are in {}",
            profdata.display(),
            profile_dir.display()
        );
        return Ok(());
    }
    let merged = profile_dir.join("merged.profdata");
    println!("pgo: step 3/4 — llvm-profdata merge");
    let status = std::process::Command::new(&merge_bin)
        .args(["merge", "-output="])
        .arg(&merged)
        .arg(&profile_dir)
        .status()
        .map_err(|e| format!("llvm-profdata: {e}"))?;
    if !status.success() {
        return Err("pgo: profdata merge failed".to_owned());
    }
    println!("pgo: step 4/4 — rebuild with -Cprofile-use");
    let status = std::process::Command::new("cargo")
        .env("RUSTFLAGS", format!("-Cprofile-use={}", merged.display()))
        .args(["build", "--release", "-p", "halyard-cli"])
        .status()
        .map_err(|e| format!("cargo build: {e}"))?;
    if !status.success() {
        return Err("pgo: profile-use build failed".to_owned());
    }
    println!(
        "pgo: walkthrough complete (release profile data at {})",
        merged.display()
    );
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn percentiles_interpolate() {
        let mut samples = Vec::new();
        for i in 0..100u32 {
            samples.push(f64::from(i));
        }
        let mut sorted = samples.clone();
        sorted.sort_by(f64::total_cmp);
        assert!((percentile_sorted(&sorted, 0.5) - 49.5).abs() < 1e-9);
        assert!((percentile_sorted(&sorted, 0.99) - 98.01).abs() < 1e-9);
        assert_eq!(percentile_sorted(&[], 0.5), 0.0);
    }

    #[test]
    fn measurement_row_shape_matches_perf_parser() {
        let budgets: Budgets =
            toml::from_str("[[budget]]\nscenario = \"no-op-warm\"\np50_ms = 8\np99_ms = 20\n")
                .expect("budget");
        assert_eq!(budgets.budget.first().expect("row").scenario, "no-op-warm");
        let m: Measurements =
            toml::from_str("[[measurement]]\nscenario = \"x\"\np50_ms = 1.5\np99_ms = 2.5\n")
                .expect("measurement");
        assert_eq!(m.measurement.first().expect("row").p50_ms, 1.5);
    }
}
